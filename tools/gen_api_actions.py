#!/usr/bin/env python3
"""Generate API_ACTIONS.md -- every catalog plugin's actions -- from the manifests.

    python3 tools/gen_api_actions.py           # rewrite API_ACTIONS.md
    python3 tools/gen_api_actions.py --check   # exit 1 if it is out of date (deploy.sh)

Generated, never hand-edited: the manifests are the source of truth, so the list a
script writer reads cannot drift from what the core will accept.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "API_ACTIONS.md")


def render():
    lines = ["# Instrument actions — generated reference", "",
             "Generated by `tools/gen_api_actions.py` from `catalog/*/manifest.json`. **Do not edit by hand.**",
             "", "Every action is sent as", "",
             "```json", '{"instrument": "<id on your bench>", "action": "<name>", "args": {...}}', "```", "",
             "to `POST api/action` (see [API.md](API.md)), or from Python as",
             "`bench.act(id, name, **args)`. **Confirm** means the core refuses the call without",
             '`"confirmed": true` in `args`. Every instrument also takes the core\'s own `power_on`',
             "and `power_off`.", ""]
    for name in sorted(os.listdir(os.path.join(HERE, "catalog"))):
        p = os.path.join(HERE, "catalog", name, "manifest.json")
        if not os.path.isfile(p):
            continue
        m = json.load(open(p, encoding="utf-8"))
        lines += [f"## {m['model']} — `{m['id']}` v{m['version']}", "",
                  f"{m['name']}. Capabilities: {', '.join(m.get('capabilities', []))}. "
                  f"Has outputs: {'**yes**' if m['has_output'] else 'no'}.", "",
                  ]
        man = m.get("manual") or {}
        if man:
            lines += [f"Manual: {man.get('title')}" + (f", {man['part']}" if man.get("part") else "")
                      + (f" ({man['edition']})" if man.get("edition") else "") + ".", ""]
        lines += ["| Action | What it does | Args | Example | Confirm |", "|---|---|---|---|---|"]
        for a, spec in sorted(m.get("actions", {}).items()):
            c = spec.get("confirm")
            conf = ("always" if c == "always" else
                    "when " + ", ".join(f"`{k}` is `{json.dumps(v)}`" for k, v in c["when"].items())
                    if isinstance(c, dict) else "")
            args = "<br>".join(
                f"`{n}`: {x.get('type')}" + (f" {x['unit']}" if x.get("unit") else "")
                + (" ∈ " + "\\|".join(str(v) for v in x["choices"]) if x.get("choices") else "")
                for n, x in (spec.get("args") or {}).items()) or "—"
            doc = (spec.get("doc") or "").replace("|", "\\|")
            if spec.get("scpi"):
                doc += f"<br>sends `{spec['scpi'].replace('|', '/')}`" + (f" ({spec['ref']})" if spec.get("ref") else "")
            lines.append(f"| `{a}` | {doc} | {args} | `{json.dumps(spec.get('example', {}))}` | {conf} |")
        st = m.get("state") or {}
        if st:
            lines += ["", "State fields (`bench.read(id)[...]`): "
                      + ", ".join(f"`{k}`" + (f" ({v['unit']})" if v.get("unit") else "") for k, v in st.items()) + "."]
        lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("API_ACTIONS.md is out of date -- run tools/gen_api_actions.py")
        print("API_ACTIONS.md is up to date")
        return
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
